#!/usr/bin/env python3
"""The half-band ÷2 filter of the rate stages (docs/FPGA.md, design 5).

Passband to 0.474 of the OUTPUT rate (0.237 of the input), stopband from
0.526 of the output (0.263 of the input): the alias of the band's edge
lands beyond CW Skimmer's usable 45.5/91/182 kHz. Kaiser window for
-96 dB (as Pavel's FIR, 1/2^16). Writes hb.tcl (the coefficients for
block_design.tcl) and prints the measured response.

    python3 hb.py [L]      L = taps, 4k+3 (default 239)
"""
import sys, numpy as np

L = int(sys.argv[1]) if len(sys.argv) > 1 else 239
assert L % 4 == 3, "a half-band of length 4k+3 has nonzero end taps"
A = 96.0
beta = 0.1102 * (A - 8.7)
n = np.arange(L) - (L - 1) / 2
h = 0.5 * np.sinc(n / 2) * np.kaiser(L, beta)
h[(n != 0) & (n % 2 == 0)] = 0.0          # exact zeros: the half-band's own
h /= h.sum()

F = np.fft.rfft(h, 1 << 18)
f = np.linspace(0, 0.5, F.size)            # of the input rate
mag = 20 * np.log10(np.abs(F) + 1e-30)
pb = mag[f <= 0.237]
sb = mag[f >= 0.263]
print(f"L={L} beta={beta:.3f} passband ripple {pb.max():+.6f}/{pb.min():+.6f} dB, "
      f"stopband max {sb.max():.1f} dB, nonzero taps {np.count_nonzero(h)}")

with open(__file__.replace("hb.py", "hb.tcl"), "w") as o:
    o.write("# generated by hb.py — do not edit\n")
    o.write(f"# L={L} pass 0.237 stop 0.263 of the input rate, {sb.max():.1f} dB\n")
    o.write("set hb_coef {" + ", ".join(f"{x:.10e}" for x in h) + "}\n")
