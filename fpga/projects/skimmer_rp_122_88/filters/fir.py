#!/usr/bin/env python3
"""The FIR ÷2 after the two CICs (768 → 384 kHz; docs/FPGA.md, design 4).

Pavel's rx_fir_0.r method (frequency sampling + Kaiser, fir2), for this
design's CICs: ÷8 with 4 stages at 122.88 MHz, then ÷20 with 6 stages.
The passband (to 0.237 of the input = 0.474 of the output rate)
compensates their droop; the stopband starts at 0.263 (the alias of the
edge lands beyond CW Skimmer's 364 kHz at 384 k), -96 dB.
Writes fir.tcl and prints the measured response.

    python3 fir.py [L]     L = taps (default 255)
"""
import sys, numpy as np

L = int(sys.argv[1]) if len(sys.argv) > 1 else 255
FS = 122.88e6
R1, N1, R2, N2 = 8, 4, 20, 6
fs_in = FS / R1 / R2                           # 768 kHz
fp, fstop, A = 0.237, 0.263, 101.0   # 96 dB + the step of the compensation (5 dB)


def cic(f_hz):
    """|H| of both CICs at f (Hz), normalised to 1 at DC."""
    def one(f, fs, r, n):
        x = np.pi * f / fs
        with np.errstate(invalid="ignore", divide="ignore"):
            h = np.where(x == 0, 1.0, np.sin(r * x) / (r * np.sin(x)))
        return np.abs(h) ** n
    return one(f_hz, FS, R1, N1) * one(f_hz, FS / R1, R2, N2)


beta = 0.1102 * (A - 8.7)
# fir2: the desired response on a dense grid, inverse FFT, Kaiser window
nfft = 1 << 16
f = np.linspace(0, 0.5, nfft // 2 + 1)        # of the input rate
# a step at the middle of the transition; the window makes the transition
d = np.where(f <= (fp + fstop) / 2, 1.0 / cic(f * fs_in), 0.0)
h = np.fft.irfft(d, nfft)
h = np.roll(h, (L - 1) // 2)[:L] * np.kaiser(L, beta)
h /= h.sum()

F = np.fft.rfft(h, 1 << 18)
ff = np.linspace(0, 0.5, F.size)
tot = np.abs(F) * cic(ff * fs_in)              # FIR × CICs: should be flat
pb = 20 * np.log10(tot[ff <= fp])
sb = 20 * np.log10(np.abs(F[ff >= fstop]) + 1e-30)
print(f"L={L}: CICs+FIR passband {pb.max():+.4f}/{pb.min():+.4f} dB, "
      f"FIR stopband max {sb.max():.1f} dB, max |h| {np.abs(h).max():.4f}")

with open(__file__.replace("fir.py", "fir.tcl"), "w") as o:
    o.write("# generated by fir.py — do not edit\n")
    o.write(f"# L={L}: CIC ÷8×4 + ÷20×6 compensated to 0.237, stop 0.263 of 768 kHz, {sb.max():.1f} dB\n")
    o.write("set fir_coef {" + ", ".join(f"{x:.10e}" for x in h) + "}\n")
